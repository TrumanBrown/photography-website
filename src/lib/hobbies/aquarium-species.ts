/**
 * Species roster for the planted-aquarium sandbox.
 *
 * Pure data: no DOM, no window. AquariumTank.astro imports it in frontmatter to
 * render the species picker at build time, and the canvas engine in
 * aquarium.ts reads the same entries for sprites and bioload.
 *
 * `color` and `accent` are the sprite colors. The picker's two-color swatch
 * reuses them, so a swatch always matches the fish it adds.
 */

export type Zone = "top" | "mid" | "bottom";
export type Shape =
  | "fish"
  | "tall"
  | "long"
  | "gourami"
  | "betta"
  | "angelfish"
  | "shrimp"
  | "snail";

export interface Species {
  id: string;
  name: string;
  /** Approx adult length in inches — drives on-screen size and bioload. */
  adultInches: number;
  /** Relative bioload (waste) contributed per individual. */
  bioload: number;
  /** Suggested minimum tank in gallons; a gentle warning shows if exceeded. */
  minGallons: number;
  zone: Zone;
  shape: Shape;
  /** Primary body color. */
  color: string;
  /** Secondary color for fins / stripe / detail. */
  accent: string;
}

