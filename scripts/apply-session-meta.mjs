#!/usr/bin/env node
/**
 * Push session titles, locations and descriptions from scripts/session-meta.json
 * into each session's `_session.json` sidecar in the `originals` container.
 *
 * Usage:
 *   AZURE_STORAGE_ACCOUNT=<account> node scripts/apply-session-meta.mjs [options]
 *
 * Options:
 *   --dry-run          Print what would change without writing anything
 *   --only <slug>      Apply a single session (repeatable)
 *   --include-drafts   Also publish entries still marked "draft": true
 *
 * Each sidecar is read, merged, and written back, so fields this file doesn't
 * manage (cover, order, date, per-image captions) survive untouched. Sessions
 * listed here that don't exist in Blob Storage are reported and skipped.
 *
 * Entries marked `"draft": true` were generated by scripts/describe-sessions.mjs
 * and are held back until you've read them, because unreviewed generated copy is
 * worse for the site than no copy at all.
 *
 * The site picks the change up on the next build. Auth uses
 * DefaultAzureCredential (your `az login` locally, OIDC in CI).
 */
import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";
import { BlobServiceClient } from "@azure/storage-blob";
import { DefaultAzureCredential } from "@azure/identity";
import { sanitizeSlug } from "./prebuild.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const META_FILE = join(ROOT, "scripts/session-meta.json");
const CONTAINER = "originals";
const SESSION_JSON = "_session.json";
/** Fields this script owns. Everything else in a sidecar is left alone. */
const MANAGED = ["title", "location", "description"];

function parseArgs(argv) {
  const only = [];
  let dryRun = false;
  let includeDrafts = false;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--dry-run") dryRun = true;
    else if (argv[i] === "--include-drafts") includeDrafts = true;
    else if (argv[i] === "--only") only.push(argv[++i]);
    else {
      console.error(`Unknown argument: ${argv[i]}`);
      process.exit(2);
    }
  }
  return { dryRun, only, includeDrafts };
}

/**
 * Map each session slug to its real blob prefix.
 *
 * The folder name in `originals/` is not always the slug: prebuild lowercases
 * it and replaces anything non-alphanumeric, so a folder like "Lijiang May
 * 2026" publishes as "lijiang-may-2026". Resolving through the same transform
 * is the only reliable way to find a session's sidecar.
 */
async function prefixesBySlug(container) {
  const map = new Map();
  for await (const item of container.listBlobsByHierarchy("/")) {
    if (item.kind !== "prefix") continue;
    const prefix = item.name.replace(/\/$/, "");
    map.set(sanitizeSlug(prefix), prefix);
  }
  return map;
}

async function readSidecar(container, prefix) {
  try {
    const buf = await container
      .getBlobClient(`${prefix}/${SESSION_JSON}`)
      .downloadToBuffer();
    return JSON.parse(buf.toString("utf8"));
  } catch (err) {
    if (err.statusCode === 404) return null;
    throw err;
  }
}

async function hasImages(container, prefix) {
  // A session is a prefix with at least one blob under it. `_session.json`
  // alone doesn't count, since prebuild ignores image-less sessions.
  for await (const blob of container.listBlobsFlat({ prefix: `${prefix}/` })) {
    if (!blob.name.endsWith(`/${SESSION_JSON}`)) return true;
  }
  return false;
}

async function main() {
  const { dryRun, only, includeDrafts } = parseArgs(process.argv.slice(2));

  const account = process.env.AZURE_STORAGE_ACCOUNT;
  if (!account) {
    console.error(
      "AZURE_STORAGE_ACCOUNT env var is required (the storage account name).",
    );
    process.exit(1);
  }

  const raw = JSON.parse(await readFile(META_FILE, "utf8"));
  const entries = Object.entries(raw).filter(([slug]) => !slug.startsWith("$"));
  const chosen =
    only.length > 0 ? entries.filter(([slug]) => only.includes(slug)) : entries;
  const heldBack = includeDrafts
    ? []
    : chosen.filter(([, meta]) => meta.draft).map(([slug]) => slug);
  const selected = includeDrafts
    ? chosen
    : chosen.filter(([, meta]) => !meta.draft);

  if (selected.length === 0) {
    if (heldBack.length > 0) {
      console.error(
        `Every selected entry is still a draft: ${heldBack.join(", ")}`,
      );
      console.error(
        'Review them in scripts/session-meta.json and remove "draft": true, or pass --include-drafts.',
      );
    } else {
      console.error(
        "Nothing to apply. Check the --only slugs against scripts/session-meta.json.",
      );
    }
    process.exit(1);
  }

  const container = new BlobServiceClient(
    `https://${account}.blob.core.windows.net`,
    new DefaultAzureCredential(),
  ).getContainerClient(CONTAINER);

  let changed = 0;
  let unchanged = 0;
  const missing = [];
  const prefixes = await prefixesBySlug(container);

  for (const [slug, meta] of selected) {
    const prefix = prefixes.get(slug);
    if (!prefix || !(await hasImages(container, prefix))) {
      missing.push(slug);
      continue;
    }

    const existing = (await readSidecar(container, prefix)) ?? {};
    const merged = { ...existing };
    const diffs = [];
    for (const field of MANAGED) {
      if (meta[field] === undefined) continue;
      if (existing[field] === meta[field]) continue;
      merged[field] = meta[field];
      diffs.push(field);
    }

    if (diffs.length === 0) {
      unchanged++;
      continue;
    }

    console.log(`${slug}: ${diffs.join(", ")}`);
    if (!dryRun) {
      const body = JSON.stringify(merged, null, 2) + "\n";
      await container
        .getBlockBlobClient(`${prefix}/${SESSION_JSON}`)
        .upload(body, Buffer.byteLength(body), {
          blobHTTPHeaders: { blobContentType: "application/json" },
        });
    }
    changed++;
  }

  console.log();
  console.log(
    `${changed} session(s) ${dryRun ? "would change" : "updated"}, ${unchanged} already current.`,
  );
  if (heldBack.length > 0) {
    console.log(`Held back as unreviewed drafts: ${heldBack.join(", ")}`);
  }
  if (missing.length > 0) {
    console.log(`Not found in ${CONTAINER}/: ${missing.join(", ")}`);
  }
  if (!dryRun && changed > 0) {
    console.log(
      'Trigger a build to publish: click "Run workflow" on build-and-deploy, or use the admin page.',
    );
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
